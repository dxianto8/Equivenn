import { expect, test } from '@playwright/test'
import { onboard } from './helpers'

test.beforeEach(async ({ page }) => { await onboard(page) })

test('review, submit, approve, recalculate, publish, persist, and export a cycle', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Big ideas. Fair opportunities.')
  await expect(page.locator('.stat-value').nth(1)).toHaveText('$112,800')
  await page.getByRole('button', { name: 'View Green Campus Initiative', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Why this allocation?' })).toBeVisible()
  await page.getByRole('button', { name: 'Done', exact: true }).click()

  await page.getByRole('button', { name: 'New request', exact: true }).click()
  await page.getByLabel('Organization name', { exact: true }).fill('Campus Coding Society')
  await page.getByLabel('Area of impact').selectOption('Academic')
  await page.getByLabel('Funding requested').fill('12500')
  await page.getByLabel('Active members', { exact: true }).fill('150')
  await page.getByLabel('Community impact score').fill('88')
  await page.getByLabel('Previous funding utilization').fill('90')
  await page.getByLabel('What will this funding make possible?').fill('Open coding workshops and equipment for students of all backgrounds.')
  await page.getByRole('button', { name: 'Submit request', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Campus Coding Society' })).toContainText('In review')
  await page.getByRole('button', { name: 'View Campus Coding Society', exact: true }).click()
  await page.getByRole('button', { name: 'Approve request', exact: true }).click()
  await page.getByRole('button', { name: 'Approved', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Campus Coding Society' })).toContainText('Approved')

  await page.getByLabel('Search organizations', { exact: true }).fill('Coding')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByLabel('Search organizations', { exact: true }).fill('')
  await page.getByLabel('Filter by category').selectOption('Arts & culture')
  await expect(page.locator('tbody tr')).toHaveCount(2)

  await page.locator('nav').getByRole('button', { name: 'Overview', exact: true }).click()
  await page.getByRole('button', { name: 'View model', exact: true }).click()
  await page.getByLabel('Total funding pool', { exact: true }).fill('150000')
  await expect(page.locator('.model-preview')).toContainText('$141,000.00')
  await page.getByRole('button', { name: 'Save & recalculate', exact: true }).click()
  await expect(page.locator('.stat-value').first()).toHaveText('$150,000')
  await expect(page.locator('.stat-value').nth(1)).toHaveText('$141,000')

  await page.locator('nav').getByRole('button', { name: 'Public ledger', exact: true }).click()
  await page.getByRole('button', { name: 'Publish allocation', exact: true }).click()
  await page.getByRole('button', { name: 'Publish record', exact: true }).click()
  await expect(page.getByText('PUBLISHED RECORD', { exact: true })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download record', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('equivenn-fall-2026-allocation.csv')
  await page.reload()
  await expect(page.locator('.stat-value').first()).toHaveText('$150,000')
  await page.locator('nav').getByRole('button', { name: 'Public ledger', exact: true }).click()
  await expect(page.getByText('PUBLISHED RECORD', { exact: true })).toBeVisible()
  await expect(page.locator('tbody tr')).toHaveCount(9)
  await page.locator('nav').getByRole('button', { name: 'Organizations', exact: true }).click()
  await expect(page.locator('.organization-card')).toHaveCount(9)
  await page.locator('nav').getByRole('button', { name: 'Analytics', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'A community-wide investment' })).toBeVisible()
  expect(errors).toEqual([])
})

test('mobile navigation and request form work without page overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.locator('nav').getByRole('button', { name: 'Organizations', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Meet your changemakers.')
  await expect(page.locator('.sidebar')).not.toHaveClass(/is-open/)
  await page.getByRole('button', { name: 'New request', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
})
