import { expect, test } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { onboard, signOut, testPassword } from './helpers'

test('first visit is gated; account setup resumes after reload; school details are required', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Big ideas start with you.' })).toBeVisible()
  await expect(page.locator('.app-shell')).toHaveCount(0)
  const privateDatabase = await page.request.get('/.data/equivenn.sqlite')
  expect(privateDatabase.status()).toBe(403)
  const email = `onboarding-${randomUUID()}@northbridge.edu`
  await page.getByLabel('Full name', { exact: true }).fill('Taylor Rivers')
  await page.getByLabel('Email address', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('short')
  await page.getByRole('button', { name: 'Create my account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Big ideas start with you.' })).toBeVisible()
  await page.getByLabel('Password', { exact: true }).fill(testPassword)
  await page.getByRole('button', { name: 'Show password', exact: true }).click()
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Create my account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Where will you make an impact?' })).toBeVisible()
  await expect(page.locator('.app-shell')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Where will you make an impact?' })).toBeVisible()
  await page.getByLabel('School name', { exact: true }).fill('Northbridge University')
  await page.getByLabel('School domain', { exact: true }).fill('northbridge.edu')
  await page.getByLabel('Your school email', { exact: true }).fill('person@another.edu')
  await page.getByRole('button', { name: 'Connect my school', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('@northbridge.edu')
  await page.getByLabel('Your school email', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Connect my school', exact: true }).click()
  await page.getByLabel('Workspace name', { exact: true }).fill('Student Council')
  await page.getByLabel('Your funding pool (USD)', { exact: true }).fill('75000')
  await page.getByRole('button', { name: 'Open my workspace', exact: true }).click()
  await expect(page.locator('.stat-value').first()).toHaveText('$75,000')
  await expect(page.locator('.workspace-switch')).toContainText('Northbridge University')
  await expect(page.locator('.workspace-switch')).toContainText('Student Council')
  await expect(page.locator('.sidebar-user')).toContainText('Taylor Rivers')
  await expect(page.locator('tbody tr')).toHaveCount(0)
  expect(await page.evaluate(() => document.cookie.includes('equivenn_session'))).toBe(false)
  const session = await (await page.request.get('/api/session')).json()
  expect(session.school.verified).toBe(false)
  expect(session.school.name).toBe('Northbridge University')
})

test('sign-out protects the dashboard, login returns to the school, and accounts keep separate data', async ({ page }) => {
  const first = await onboard(page)
  await page.getByRole('button', { name: 'View model', exact: true }).click()
  await page.getByLabel('Total funding pool', { exact: true }).fill('91000')
  await page.getByRole('button', { name: 'Save & recalculate', exact: true }).click()
  await expect(page.locator('.stat-value').first()).toHaveText('$91,000')
  await signOut(page)
  await expect(page.locator('.app-shell')).toHaveCount(0)
  await page.getByLabel('Email address', { exact: true }).fill(first.email)
  await page.getByLabel('Password', { exact: true }).fill('incorrect password')
  await page.getByRole('button', { name: 'Sign in to Equivenn', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('does not match')
  await page.getByLabel('Password', { exact: true }).fill(first.password)
  await page.getByRole('button', { name: 'Sign in to Equivenn', exact: true }).click()
  await expect(page.locator('.stat-value').first()).toHaveText('$91,000')
  await page.reload()
  await expect(page.locator('.stat-value').first()).toHaveText('$91,000')
  await signOut(page)
  await page.getByRole('button', { name: 'Create an account', exact: true }).click()
  await onboard(page, { budget: 12345 })
  await expect(page.locator('.stat-value').first()).toHaveText('$12,345')
  await expect(page.locator('tbody tr')).toHaveCount(0)
  await signOut(page)
  await page.getByLabel('Email address', { exact: true }).fill(first.email)
  await page.getByLabel('Password', { exact: true }).fill(first.password)
  await page.getByRole('button', { name: 'Sign in to Equivenn', exact: true }).click()
  await expect(page.locator('.stat-value').first()).toHaveText('$91,000')
  await expect(page.locator('tbody tr')).toHaveCount(0)
})

